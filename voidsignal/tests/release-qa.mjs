import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const file=x=>fs.readFileSync(path.join(root,x),'utf8');
const html=file('index.html'),css=file('style.css'),js=file('app.mjs'),sw=file('sw.js'),privacy=file('privacy.html');
const allIds=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(allIds).size,allIds.length,'Duplicate HTML IDs');
for(const id of [...js.matchAll(/\$\('([^']+)'\)/g)].map(m=>m[1])) assert.ok(allIds.includes(id),'Missing HTML control '+id);
for(const id of ['pause','resume','pause-overlay','settings-overlay','settings-close','settings-done','daily-play','play','result-overlay','update-banner','update-reload']) assert.ok(allIds.includes(id));
assert.ok(html.includes('30 neon missions'));
assert.ok(html.includes('https://weirdflex.online/voidsignal/assets/cover.png'));
assert.ok(html.includes('privacy.html')&&privacy.includes('localStorage'));
assert.ok(js.includes("'voidsignal.v02.progress'"),'Old campaign data should be preserved');
for(const name of [...html.matchAll(/(?:src|href)="(\.\/[^"?#]+)"/g)].map(m=>m[1])) assert.ok(fs.existsSync(path.join(root,name)),'Missing asset '+name);
for(const name of [...css.matchAll(/url\(['"]?(\.\/[^'"\)]+)['"]?\)/g)].map(m=>m[1])) assert.ok(fs.existsSync(path.join(root,name)),'Missing CSS asset '+name);
const cached=[...sw.matchAll(/'((?:\.\/)[^']+)'/g)].map(m=>m[1]);
for(const name of cached)assert.ok(fs.existsSync(path.join(root,name)),'SW missing '+name);
assert.ok(cached.includes('./privacy.html'));
assert.ok(cached.includes('./game-engine.mjs'));
const fxNames=[...js.matchAll(/'((?:core|burst|shockwave|comet|nova|collapse)[^']*)'/g)].map(m=>m[1]);
for(const name of fxNames)assert.ok(fs.existsSync(path.join(root,'assets/fx',name+'.png')),'FX missing '+name);
const manifest=JSON.parse(file('manifest.webmanifest'));
assert.equal(manifest.display,'standalone');
for(const icon of manifest.icons)assert.ok(fs.existsSync(path.join(root,icon.src)));
assert.ok(css.includes(':focus-visible'));
console.log('PASS: unique IDs and referenced controls');
console.log('PASS: all linked CSS, HTML, PWA and FX assets exist');
console.log('PASS: game and privacy metadata, original save keys, controls, and offline assets');
